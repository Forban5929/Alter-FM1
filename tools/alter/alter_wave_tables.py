"""WAVE engine (v1.16): the four wavetables Romain kept after the listening rounds (CLANG RUST SHRED FEEDBACK,
tools/alter/alter_wave_wav.py), written as a C header for firmware/src/eng_wave.c.
Each table: 16 frames; each frame in 4 band-limited copies (mip levels): 256 points with harmonics 1..64, 128 / 32,
64 / 16, 32 / 8. Stored as int8 (peak at 127) with one gain per frame (Q12) that brings every frame back to the same
loudness (RMS), so a POS sweep stays level. Original tables synthesised here (no third-party data).
    python3 tools/alter/alter_wave_tables.py > firmware/src/eng_wave_tab.h
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import alter_wave_wav as W  # noqa: E402

W.band = lambda x: x                               # the raw cycle (HIRES points): band-limited per mip below
TABS = ["CLANG", "RUST", "SHRED", "FEEDBACK"]
FRAMES = 16
MIPS = [(256, 64), (128, 32), (64, 16), (32, 8)]   # (points, harmonics)


def mip(x, n, h):
    X = np.fft.rfft(x)
    X[0] = 0
    X[h + 1:] = 0
    y = np.fft.irfft(X, len(x))
    return y[:: len(x) // n]


def main():
    out = ["/* generated by tools/alter/alter_wave_tables.py: do not edit (WAVE engine tables, v1.16) */",
           f"#define WV_NTAB {len(TABS)}", f"#define WV_NFR {FRAMES}",
           "/* [table][frame]: 256 + 128 + 64 + 32 points (mip 0..3) */",
           "static const int8_t WV_TAB[WV_NTAB][WV_NFR][480] = {"]
    gains = []
    for name in TABS:
        fn = getattr(W, "t_" + name.lower())
        out.append(f"/* {name} */ {{")
        gl = []
        for fr in range(FRAMES):
            x = fn(fr / (FRAMES - 1))
            ms = [mip(x, n, h) for n, h in MIPS]
            rms = np.sqrt(np.mean(ms[0] ** 2)) + 1e-12
            pk = max(np.max(np.abs(m)) for m in ms) + 1e-12
            q = [np.clip(np.round(m / pk * 127), -127, 127).astype(int) for m in ms]
            gl.append(int(round(4096 * 127 * 0.25 / (rms / pk * 127))))   # x the int8 -> RMS 0.25 of 127 (Q12)
            v = np.concatenate(q)
            out.append(" {" + ",".join(str(int(a)) for a in v) + "},")
        out.append("},")
        gains.append(gl)
    out.append("};")
    out.append("static const uint16_t WV_GAIN[WV_NTAB][WV_NFR] = {")
    for gl in gains:
        out.append(" {" + ",".join(str(g) for g in gl) + "},")
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
